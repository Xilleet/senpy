from __future__ import annotations

import contextlib
import json
import os
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from senpy.analyzer import SenpyAnalyzer

RENPY_PYI_TEMPLATE = """# Type stubs for Ren'Py Engine (Generated by Senpy)
from typing import Any, Callable, Optional, Sequence, Union

class _Music:
    @staticmethod
    def play(filename: str, channel: str = "music", loop: Optional[bool] = None, fadein: float = 0, fadeout: float = 0, synchro: bool = False, if_changed: bool = False) -> None: ...
    @staticmethod
    def stop(channel: str = "music", fadeout: float = 0) -> None: ...
    @staticmethod
    def queue(filename: str, channel: str = "music", loop: Optional[bool] = None, clear_queue: bool = True, fadein: float = 0, tight: Optional[bool] = None) -> None: ...
    @staticmethod
    def register_channel(name: str, mixer: str = "sfx", loop: bool = False, stop_on_mute: bool = True, tight: bool = False, file_prefix: str = "", file_suffix: str = "", buffer_queue: bool = True) -> None: ...

music: _Music

def jump(label: str) -> None: ...
def call(label: str, *args: Any, **kwargs: Any) -> Any: ...
def return_statement(value: Any = None) -> None: ...
def pause(delay: Optional[float] = None, music: Optional[bool] = None, hard: bool = False) -> bool: ...
def notify(message: str) -> None: ...
def restart_interaction() -> None: ...
def full_restart(transition: Any = False) -> None: ...
def quit(relaunch: bool = False, status: int = 0) -> None: ...

class _Random:
    def random(self) -> float: ...
    def randint(self, a: int, b: int) -> int: ...
    def choice(self, seq: Sequence[Any]) -> Any: ...
    def shuffle(self, x: list[Any]) -> None: ...

random: _Random
"""


def generate_stubs(analyzer: SenpyAnalyzer, out_dir: str = "typings") -> tuple[str, int]:
    """Генерирует файлы заглушек .pyi для Pylance/MyPy на основе собранных символов."""
    project_root = analyzer.project_path
    target_dir = os.path.join(project_root, out_dir)
    os.makedirs(target_dir, exist_ok=True)

    # 1. Генерируем renpy.pyi
    renpy_pyi = os.path.join(target_dir, "renpy.pyi")
    with open(renpy_pyi, "w", encoding="utf-8", newline="\n") as f:
        f.write(RENPY_PYI_TEMPLATE)

    # 2. Генерируем store.pyi с типами переменных проекта
    type_map = {
        "int": "int",
        "float": "float",
        "str": "str",
        "bool": "bool",
        "list": "list[Any]",
        "dict": "dict[str, Any]",
        "set": "set[Any]",
    }

    store_lines = [
        "# Project State & Store Stubs (Generated by Senpy)",
        "from typing import Any, Optional",
        "import renpy",
        "",
        "# Built-in Ren'Py Singletons",
        "persistent: Any",
        "config: Any",
        "gui: Any",
        "style: Any",
        "",
        "# Project Variables & Constants",
    ]

    symbols_count = 0
    for var in sorted(analyzer.declared_symbols):
        if var.startswith("_") or var in ("renpy", "config", "persistent", "gui", "style", "store"):
            continue
        # Пропускаем имена встроенных модулей python
        if var in ("True", "False", "None"):
            continue

        var_sym = analyzer.variables.get(var)
        var_type = var_sym.type_name if var_sym else None
        py_type = type_map.get(var_type, "Any")
        store_lines.append(f"{var}: {py_type}")
        symbols_count += 1

    store_pyi = os.path.join(target_dir, "store.pyi")
    with open(store_pyi, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(store_lines) + "\n")

    # 3. Настраиваем .vscode/settings.json, если он есть
    vscode_dir = os.path.join(project_root, ".vscode")
    settings_json = os.path.join(vscode_dir, "settings.json")
    if os.path.isdir(vscode_dir):
        with contextlib.suppress(OSError, json.JSONDecodeError, UnicodeDecodeError):
            data = {}
            if os.path.exists(settings_json):
                with open(settings_json, encoding="utf-8") as f:
                    data = json.load(f)
            extra_paths = data.get("python.analysis.extraPaths", [])
            rel_out = out_dir.replace("\\", "/")
            if rel_out not in extra_paths and f"./{rel_out}" not in extra_paths:
                extra_paths.append(f"./{rel_out}")
                data["python.analysis.extraPaths"] = extra_paths
                with open(settings_json, "w", encoding="utf-8") as f:
                    json.dump(data, f, indent=4, ensure_ascii=False)

    return target_dir, symbols_count
